"""Derived engineering constants (E2, nu23, E1, nu12) recomputed after the nu12 sign fix in micromech.hill_longitudinal
(2026-10-17 16:03, see results/PROTOCOL.md). The moduli predictions are regenerated by refitting each method with the
draws and seeds of scripts/run_budget.py; every refit is checked to reproduce the stored MAPE of G12, G23 and k23
(relative difference < 1e-6), so only the derived constants change.
Usage: python3 -I scripts/derived_v2.py METHODS OUT.csv [BUDGETS]     e.g. BN-COR,MT,LF,RICH results/test_derived_v2_a.csv"""
import sys, os, json, glob
import numpy as np, pandas as pd
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, ROOT); os.chdir(ROOT)
from mfhomog import data as D, surrogates as S, nn_models as NN

methods, outp = sys.argv[1].split(','), sys.argv[2]
BUDGETS = [int(b) for b in sys.argv[3].split(',')] if len(sys.argv) > 3 else [10, 20, 40, 80, 160]
LFLEV, RATIO = 128, 4
pool = D.load('data/pool.jsonl'); lfx = D.load('data/lfx.jsonl'); ev = D.load('data/test.jsonl')
XP, YP, LOP, UPP = D.arrays(pool, 'HF'); _, YP_L, _, _ = D.arrays(pool, LFLEV); XX, YX_L, LOX, UPX = D.arrays(lfx, LFLEV)
XE, YE, LOE, UPE = D.arrays(ev, 'HF'); _, YE_L, _, _ = D.arrays(ev, LFLEV); _, YE64, _, _ = D.arrays(ev, 64); _, YE_M, _, _ = D.arrays(ev, 128)
HP = json.load(open('results/nn_hparams.json'))
old = pd.concat([pd.read_csv(f) for f in glob.glob('results/test_[ABCD].csv')])
Et = np.array([D.engineering_from(r, y) for r, y in zip(ev, YE)])


def model(name, nH, seed):
    h = HP.get(name, {}).get(str(nH), {})
    return {'BN-COR': lambda: S.Corrector('logit', seed), 'BN-AR1': lambda: S.RecursiveAR1('logit', seed),
            'BMLP': lambda: NN.MLP(seed=seed, bounded=True, **h), 'GP': lambda: S.GP('log', seed),
            'BN-GP': lambda: S.GP('logit', seed)}[name]()


rows = []
for name in methods:
    for nH in BUDGETS:
        for rep in range(20 if nH <= 40 else 10):
            rng = np.random.default_rng(10_000 * nH + rep)
            iH = rng.choice(len(pool), nH, replace=False); iX = rng.choice(len(lfx), (RATIO - 1) * nH, replace=False)
            XL = np.vstack([XP[iH], XX[iX]]); YL = np.vstack([YP_L[iH], YX_L[iX]])
            LOL = np.vstack([LOP[iH], LOX[iX]]); UPL = np.vstack([UPP[iH], UPX[iX]])
            if name == 'MT':
                Yp = np.array([D.analytic(r, 'MT') for r in ev])
            elif name == 'LF':
                Yp = YE_L.copy()
            elif name == 'RICH':
                Yp = 2 * YE_M - YE64
            else:
                m = model(name, nH, rep)
                m.fit(XP[iH], YP[iH], LOP[iH], UPP[iH], XL=XL, YL=YL, LOL=LOL, UPL=UPL, YLH=YP_L[iH])
                Yp = m.predict(XE, LOE, UPE, YLq=YE_L)[0]
            o = old[(old.method == name) & (old.nH == nH) & (old.rep == rep)].iloc[0]
            mape = (np.abs(Yp / YE - 1) * 100).mean(0)
            rel = max(abs(mape[j] / o[f'mape_{t}'] - 1) for j, t in enumerate(D.TARGETS))
            Ep = np.array([D.engineering_from(r, y) for r, y in zip(ev, Yp)])
            row = dict(method=name, nH=nH, rep=rep, moduli_rel_diff=float(rel), reproduced=bool(rel < 1e-6))
            for j, t in enumerate(['E2', 'nu23', 'E1', 'nu12']):
                e = np.abs(Ep[:, j] / Et[:, j] - 1) * 100
                row[f'mape_{t}'] = float(e.mean()); row[f'max_{t}'] = float(e.max())
            rows.append(row)
            pd.DataFrame([row]).to_csv(outp, mode='a', header=not os.path.exists(outp), index=False)
            if name in ('MT', 'LF', 'RICH') and rep == 0:
                break                       # deterministic methods: one row per budget is enough
        print(name, nH, 'done', flush=True)
